const supportedLanguages = ["en", "zh", "fr"];

function normalizeLanguage(input) {
  if (!input) {
    return null;
  }
  const normalized = String(input).trim().toLowerCase();
  const base = normalized.split(/[-_]/)[0];
  return supportedLanguages.includes(base) ? base : null;
}

function updatePageMetadata(table) {
  if (table.documentTitle) {
    document.title = table.documentTitle;
  }
  const descriptionNode = document.querySelector("meta[name='description']");
  if (descriptionNode && table.metaDescription) {
    descriptionNode.setAttribute("content", table.metaDescription);
  }
}

function syncLanguageToUrl(lang) {
  if (!window.history || !window.history.replaceState) {
    return;
  }

  const url = new URL(window.location.href);
  url.searchParams.set("lang", lang);
  window.history.replaceState(null, "", url.toString());
}

function lockHeroSubtitleCompoundHyphens(text) {
  return text.replace(/Role(?:[-\u2011])playing/gi, "Role\u2011playing");
}

function applyHeroSubtitleLayout() {
  const subtitle = document.querySelector(".hero-subtitle");
  if (!subtitle) {
    return;
  }

  const rawText = lockHeroSubtitleCompoundHyphens(subtitle.textContent || "");
  const parts = rawText
    .split("/")
    .map((part) => part.trim())
    .filter(Boolean);

  if (parts.length <= 1) {
    subtitle.textContent = rawText;
    return;
  }

  subtitle.textContent = "";
  parts.forEach((part, index) => {
    const item = document.createElement("span");
    item.className = "subtitle-item";
    item.textContent = part;
    subtitle.appendChild(item);

    if (index < parts.length - 1) {
      const sep = document.createElement("span");
      sep.className = "subtitle-sep";
      sep.textContent = " / ";
      subtitle.appendChild(sep);
    }
  });
}

function setLanguage(page, lang, options = {}) {
  const { persist = true, syncUrl = true } = options;
  const table = dictionaries[page] && dictionaries[page][lang];
  if (!table) {
    return;
  }

  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
  if (persist) {
    localStorage.setItem("site-lang", lang);
  }
  if (syncUrl) {
    syncLanguageToUrl(lang);
  }
  updatePageMetadata(table);

  const nodes = document.querySelectorAll("[data-i18n]");
  nodes.forEach((node) => {
    const key = node.getAttribute("data-i18n");
    if (table[key]) {
      node.textContent = table[key];
    }
  });

  applyHeroSubtitleLayout();

  const buttons = document.querySelectorAll(".lang-btn");
  buttons.forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", active ? "true" : "false");
  });
}

function initLanguageSwitcher() {
  const page = document.body.dataset.page;
  if (!page || !dictionaries[page]) {
    return;
  }

  const fromQuery = normalizeLanguage(new URLSearchParams(window.location.search).get("lang"));
  const fromStorage = normalizeLanguage(localStorage.getItem("site-lang"));
  const fromBrowser = normalizeLanguage(navigator.language || navigator.userLanguage);
  const preferred = fromQuery || fromStorage || fromBrowser || "en";
  const fallback = dictionaries[page][preferred] ? preferred : "en";
  setLanguage(page, fallback, { syncUrl: Boolean(fromQuery) });

  document.querySelectorAll(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => {
      const nextLanguage = normalizeLanguage(button.dataset.lang);
      if (!nextLanguage) {
        return;
      }
      setLanguage(page, nextLanguage);
    });
  });
}

function buildPlaceholderImage(text) {
  const safeText = (text || "Preview").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 675"><defs><linearGradient id="g" x1="0" x2="1" y1="0" y2="1"><stop offset="0%" stop-color="#eef8f2"/><stop offset="100%" stop-color="#dff2ea"/></linearGradient></defs><rect width="1200" height="675" fill="url(#g)"/><rect x="40" y="40" width="1120" height="595" rx="24" ry="24" fill="none" stroke="#9ecfba" stroke-width="5" stroke-dasharray="14 10"/><text x="600" y="352" fill="#466757" font-family="Nunito, Segoe UI, sans-serif" font-size="46" font-weight="700" text-anchor="middle">${safeText}</text></svg>`;
  return `data:image/svg+xml;charset=UTF-8,${encodeURIComponent(svg)}`;
}

function initGalleryLightbox() {
  const lightbox = document.getElementById("gallery-lightbox");
  if (!lightbox) {
    return;
  }

  const imageNode = lightbox.querySelector(".lightbox-image");
  const captionNode = lightbox.querySelector(".lightbox-caption");
  const galleryItems = document.querySelectorAll(".gallery-item");

  function closeLightbox() {
    lightbox.classList.remove("is-open");
    lightbox.setAttribute("aria-hidden", "true");
    document.body.style.overflow = "";
  }

  function openLightbox(item) {
    const label = item.innerText.trim();
    const imageChild = item.querySelector("img");
    const source = imageChild && imageChild.getAttribute("src")
      ? imageChild.getAttribute("src")
      : buildPlaceholderImage(label);

    imageNode.setAttribute("src", source);
    imageNode.setAttribute("alt", label);
    captionNode.textContent = label;

    lightbox.classList.add("is-open");
    lightbox.setAttribute("aria-hidden", "false");
    document.body.style.overflow = "hidden";
  }

  galleryItems.forEach((item) => {
    item.addEventListener("click", () => openLightbox(item));
    item.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        openLightbox(item);
      }
    });
  });

  lightbox.querySelectorAll("[data-close-lightbox='true']").forEach((node) => {
    node.addEventListener("click", closeLightbox);
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape" && lightbox.classList.contains("is-open")) {
      closeLightbox();
    }
  });
}

